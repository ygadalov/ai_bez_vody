    cx, cy = CW / 2, 98
    nodes = [(cx, cy + 66, ["1. Изменили", "инструкцию"], PURPLE),
             (cx + 165, cy, ["2. Прогнали", "контрольный набор"], B_FMT),
             (cx, cy - 66, ["3. Сравнили", "с прошлой версией"], TEAL),
             (cx - 165, cy, ["4. Лучше — сохранили", "хуже — откатили"], NAVY)]
    bw, bh = 140, 40
    for x, y, ln, c in nodes:
        rbox(d, x - bw / 2, y - bh / 2, bw, bh, c, ln, fs=8, lead=12)
    arrow(d, cx + bw / 2 + 4, cy + 60, cx + 165 - 24, cy + bh / 2 + 4, GREY)
    arrow(d, cx + 165 - 24, cy - bh / 2 - 4, cx + bw / 2 + 4, cy - 60, GREY)
    arrow(d, cx - bw / 2 - 4, cy - 60, cx - 165 + 24, cy - bh / 2 - 4, GREY)
    arrow(d, cx - 165 + 24, cy + bh / 2 + 4, cx - bw / 2 - 4, cy + 60, GREY)
    txt(d, cx, cy + 3, "версия 1.3", 8.4, NAVY, "DV-B", "middle")
    txt(d, cx, cy - 9, "от 21.10", 7.4, GREY, "DV", "middle")
    return d


