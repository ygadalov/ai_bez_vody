# Рис. 1 — пирамида устаревания
def fig_pyramid():
    d = Drawing(CW, 200)
    cx, base_w, top_y, bot_y = 150, 290, 190, 10
    bands = [("ИНСТРУМЕНТЫ", "модели, приложения, цены", "месяцы", PURPLE),
             ("ПРИЁМЫ", "структура промпта · примеры · рассуждение", "1–3 года", TEAL),
             ("ПРИНЦИПЫ", "устройство моделей · постановка задачи · проверка", "живут годы", NAVY)]
    hgt = (top_y - bot_y) / 3
    def half(y):
        return 50 + (base_w / 2 - 50) * (top_y - y) / (top_y - bot_y)
    for i, (nm, sub, life, c) in enumerate(bands):
        y1 = top_y - i * hgt; y0 = y1 - hgt
        d.add(Polygon([cx - half(y0), y0 + 2, cx + half(y0), y0 + 2, cx + half(y1), y1, cx - half(y1), y1],
                      fillColor=c, strokeColor=white, strokeWidth=1.5))
        ym = (y0 + y1) / 2
        txt(d, cx, ym - 3 + (0 if i == 0 else 4), nm, 8.6 if i else 7.6, white, "DV-B", "middle")
        if i:
            txt(d, cx, ym - 9, sub, 6.4, white, "DV", "middle")
        else:
            pass
        d.add(Line(cx + half(ym) + 4, ym, 318, ym, strokeColor=GREY, strokeWidth=0.6, strokeDashArray=[2, 2]))
        txt(d, 324, ym + 2, life, 9, c, "DV-B")
        if i == 0:
            txt(d, 324, ym - 10, sub, 7.4, GREY)
    return d

# Рис. 2 — карта курса
def fig_map():
    d = Drawing(CW, 300)
    mods = [("Модуль 1 · Как думает машина", NAVY, ["1. Что такое ИИ", "2. Как работает|языковая модель", "3. Сильные и|слабые стороны"]),
            ("Модуль 2 · Разговор с моделью", TEAL, ["4. Анатомия|промпта", "5. Техники|промптинга", "6. Документы|и данные", "7. Контроль|качества"]),
            ("Модуль 3 · Вайбкодинг", HexColor("#C9971C"), ["8. Что такое|вайбкодинг", "9. Первый|проект", "10. Агентный|режим кодинга", "11. Качество и|безопасность"]),
            ("Модуль 4 · Агенты и свой ИИ", CORAL, ["12. Что такое|ИИ-агент", "13. Агенты|без кода", "14. Агенты|в коде",
                                                   "15. Локальный|ИИ", "16. Локальный|агент + RAG", "17. Финальный|проект"])]
    y = 300
    for title, c, lessons in mods:
        y -= 16
        txt(d, 0, y, title, 8.8, c, "DV-B")
        y -= 46
        n = len(lessons); gap = 6
        bw = min(118, (CW - gap * (n - 1)) / n)
        for i, l in enumerate(lessons):
            x = i * (bw + gap)
            rbox(d, x, y, bw, 38, c, l.split("|"), fs=7.2 if n > 4 else 7.8, fc=INK if c == HexColor("#C9971C") else white,
                 bold_first=False, r=5)
            if i < n - 1:
                arrow(d, x + bw + 0.5, y + 19, x + bw + gap - 0.5, y + 19, GREY, 0.8, 3)
        y -= 12
    return d

