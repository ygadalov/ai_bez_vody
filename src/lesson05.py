# Рис. 2 — сразу ответ и по шагам
def fig_cot():
    d = Drawing(CW, 226)
    cw_ = (CW - 24) / 2
    q = "Соблюдён ли ковенант «Долг / EBITDA ≤ 3,5»?"
    for k, (title, col) in enumerate([("Сразу ответ", CORAL), ("По шагам", TEAL)]):
        x = k * (cw_ + 24)
        txt(d, x + cw_ / 2, 212, title, 9, col, "DV-B", "middle")
        rbox(d, x, 176, cw_, 26, LGREY, [q], fs=7.6, fc=INK, stroke=LINE, r=4, bold_first=False)
        arrow(d, x + cw_ / 2, 174, x + cw_ / 2, 160, GREY)
    # слева
    x = 0
    rbox(d, x, 116, cw_, 42, HexColor("#FCEAE4"), ["2 400 / 900 = 2,7", "Ковенант соблюдён"], fs=8.2,
         fc=INK, stroke=CORAL, r=4)
    txt(d, x + 4, 96, "Лизинг забыт, разовый доход не исключён.", 7.4, INK, "DV-B")
    for i, ln in enumerate(["По ответу этого не видно: проверить можно,",
                            "только пересчитав всё заново."]):
        txt(d, x + 4, 83 - i * 11, ln, 7.4, GREY, "DV-I")
    # справа
    x = cw_ + 24
    steps = ["1. Долг = кредиты 2 400 + лизинг 500 = 2 900",
             "2. EBITDA = 900 − разовый доход 80 = 820",
             "3. 2 900 / 820 ≈ 3,54"]
    for i, s in enumerate(steps):
        rbox(d, x, 130 - i * 28, cw_, 24, white, [s], fs=7.6, fc=INK, stroke=TEAL, r=4, bold_first=False)
    rbox(d, x, 18, cw_, 30, TEAL, ["Вывод: ковенант нарушен (3,54 > 3,5)"], fs=8)
    arrow(d, x + cw_ / 2, 72, x + cw_ / 2, 50, GREY)
    txt(d, x + cw_ / 2, 4, "каждый шаг можно проверить отдельно", 7.2, GREY, "DV-I", "middle")
    txt(d, cw_ / 2, 30, "Цифры условные, млн руб.", 7, GREY, "DV-I", "middle")
    return d

# Рис. 3 — цепочка промптов с контрольными точками
def fig_chain():
    d = Drawing(CW, 146)
    links = [("1. Извлечь", "показатели", "в таблицу", "таблица"),
             ("2. Сверить", "с исходной", "отчётностью", "расхождения"),
             ("3. Рассчитать", "коэффициенты", "", "коэффициенты"),
             ("4. Написать", "вывод", "для комитета", "заключение")]
    cols = [TEAL, B_FMT, NAVY, PURPLE]
    gap = 26; bw = (CW - 3 * gap) / 4; y = 48; bh = 56
    for i, ((a, b, c, out), col) in enumerate(zip(links, cols)):
        x = i * (bw + gap)
        rbox(d, x, y, bw, bh, col, [a, b, c] if c else [a, b], fs=8, lead=11.5)
        txt(d, x + bw / 2, y - 14, "→ " + out, 7.4, GREY, "DV-I", "middle")
        if i < 3:
            arrow(d, x + bw + 3, y + bh / 2, x + bw + gap - 3, y + bh / 2, GREY)
    for i in (1, 2):  # контрольные точки после звеньев 2 и 3
        gx = (i + 1) * (bw + gap) - gap / 2
        d.add(Circle(gx, y + bh + 22, 9, fillColor=GOLD, strokeColor=GOLD))
        txt(d, gx, y + bh + 19, "✓", 8.6, NAVY, "DV-B", "middle")
        d.add(Line(gx, y + bh + 13, gx, y + bh / 2 + 4, strokeColor=GOLD, strokeWidth=1, strokeDashArray=[2, 2]))
    txt(d, CW / 2 + 2, y + bh + 40, "✓ — контрольная точка: человек смотрит промежуточный результат", 7.6,
        NAVY, "DV-B", "middle")
    txt(d, CW / 2, 6, "Ошибку видно на том звене, где она возникла, — и исправлять нужно только его", 7.4,
        GREY, "DV-I", "middle")
    return d

