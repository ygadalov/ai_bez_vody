# Рис. 1 — зубчатая граница
def fig_frontier():
    d = Drawing(CW, 190)
    n = 8
    xs = [40 + i * (CW - 80) / n for i in range(n + 1)]
    ys = [62, 142, 66, 146, 58, 140, 64, 146, 60]
    poly = [0, 6, 0, 58] + sum([[x, y] for x, y in zip(xs, ys)], []) + [CW, 58, CW, 6]
    d.add(Polygon(poly, fillColor=HexColor("#CDEBE6"), strokeColor=TEAL, strokeWidth=1.4))
    txt(d, CW / 2, 178, "Снаружи: ИИ ошибается — даже в похожих на «простые» задачах", 8.2, CORAL, "DV-B", "middle")
    txt(d, CW / 2, 16, "Внутри: ИИ справляется отлично", 8.2, DTEAL, "DV-B", "middle")
    inside = [(1, ["черновик", "письма"]), (3, ["сводка", "отчёта"]), (5, ["код", "скрипта"]), (7, ["перевод"])]
    outside = [(2, ["посчитать", "буквы"]), (4, ["свежая", "новость"]), (6, ["редкий", "факт"]), (8, ["точный расчёт", "в уме"])]
    for i, ln in inside:
        x, y = xs[i], ys[i]
        d.add(Circle(x, y - 28, 4, fillColor=TEAL, strokeColor=white))
        for k, l in enumerate(ln):
            txt(d, x, y - 42 - k * 9, l, 6.9, INK, "DV", "middle")
    for i, ln in outside:
        x, y = xs[i], ys[i]
        d.add(Circle(x, y + 16, 4, fillColor=CORAL, strokeColor=white))
        for k, l in enumerate(ln):
            txt(d, x, y + 26 + (len(ln) - 1 - k) * 9, l, 6.9, INK, "DV", "middle")
    return d

