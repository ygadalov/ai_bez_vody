# Рис. 3 — цикл вайбкодинга с проверкой
def fig_loop():
    d = Drawing(CW, 150)
    steps = [(["1. Описали", "задачу"], NAVY), (["2. Получили", "код"], PURPLE),
             (["3. Запустили на", "контрольном примере"], B_FMT), (["4. Сравнили", "с известным ответом"], TEAL)]
    gap = 22; bw = (CW - 3 * gap) / 4; y = 74
    for i, (ln, c) in enumerate(steps):
        x = i * (bw + gap)
        rbox(d, x, y, bw, 46, c, ln, fs=7.8, lead=12)
        if i < 3:
            arrow(d, x + bw + 3, y + 23, x + bw + gap - 3, y + 23, GREY)
    # возврат
    xe = 3 * (bw + gap) + bw / 2
    d.add(Line(xe, y - 2, xe, 40, strokeColor=CORAL, strokeWidth=1.2))
    d.add(Line(xe, 40, bw / 2, 40, strokeColor=CORAL, strokeWidth=1.2))
    arrow(d, bw / 2, 40, bw / 2, y - 3, CORAL, 1.2)
    rbox(d, CW / 2 - 90, 30, 180, 20, CORAL_BG, ["5. Не совпало — уточнили описание"], fs=7.6, fc=INK,
         stroke=CORAL, r=4, bold_first=False)
    txt(d, xe, y + 56, "совпало — пользуемся", 7.4, DTEAL, "DV-B", "middle")
    txt(d, CW / 2, 8, "Вы проверяете не каждую строчку кода, а результат на примерах, ответ к которым знаете", 7.4,
        GREY, "DV-I", "middle")
    return d

