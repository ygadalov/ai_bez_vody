def bars(d, x0, y0, w, h, labels, vals, colors_, title=None, show_pct=True):
    n = len(vals); bw = w / n
    mx = max(vals)
    if title:
        txt(d, x0 + w / 2, y0 + h + 22, title, 8.4, NAVY, "DV-B", "middle")
    for i, (lb, v) in enumerate(zip(labels, vals)):
        bh = h * v / mx if mx else 0
        d.add(Rect(x0 + i * bw + 5, y0, bw - 10, bh, fillColor=colors_[i % len(colors_)], strokeColor=None))
        if show_pct:
            txt(d, x0 + i * bw + bw / 2, y0 + bh + 4, f"{v}%", 7.6, INK, "DV-B", "middle")
        txt(d, x0 + i * bw + bw / 2, y0 - 11, lb, 6.6, INK, "DV", "middle")

