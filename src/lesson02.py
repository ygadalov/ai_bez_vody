# Рис. 4 — внимание
def fig_attention():
    d = Drawing(CW, 150)
    def sentence(y, words, key, links, note):
        x = 10; pos = {}
        for w_ in words:
            wd = pdfmetrics.stringWidth(w_, "DV-B" if w_ == key else "DV", 10)
            txt(d, x, y, w_, 10, CORAL if w_ == key else INK, "DV-B" if w_ == key else "DV")
            pos[w_] = x + wd / 2; x += wd + 9
        for target, wdt in links:
            x1, x2 = pos[key], pos[target]
            mid = (x1 + x2) / 2; hgt = 14 + abs(x2 - x1) * 0.12
            from reportlab.graphics.shapes import Path
            p = Path(strokeColor=TEAL, strokeWidth=wdt, fillColor=None)
            p.moveTo(x1, y + 12); p.curveTo(x1, y + 12 + hgt, x2, y + 12 + hgt, x2, y + 12)
            d.add(p)
        txt(d, 330, y, note, 8.6, NAVY, "DV-B")
    sentence(92, ["Я", "снял", "деньги", "в", "банке", "у", "метро"], "банке",
             [("деньги", 3), ("снял", 1.6), ("метро", 0.8)], "→ финансовый банк")
    sentence(28, ["Мы", "сидели", "на", "банке", "реки", "с", "удочкой"], "банке",
             [("реки", 3), ("удочкой", 1.8), ("сидели", 0.8)], "→ берег реки")
    return d

