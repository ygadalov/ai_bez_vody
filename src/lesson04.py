def fig_stairs():
    d = Drawing(CW, 222)
    cols = [
        ("Переписать абзац", [("Задача", B_TASK)]),
        ("Сводка отчёта для себя", [("Задача", B_TASK), ("Контекст", B_CTX), ("Формат", B_FMT)]),
        ("Записка к кредитному комитету", [("Задача", B_TASK), ("Контекст", B_CTX), ("Формат", B_FMT),
                                           ("Ограничения", B_LIM), ("Примеры", B_EX), ("Роль", B_ROLE)]),
    ]
    bw, bh, base = 118, 19, 54
    gap = (CW - 3 * bw - 20) / 2
