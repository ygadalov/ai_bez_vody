def fig_layout():
    d = Drawing(CW, 250)
    px, pw = 30, 210
    d.add(Rect(px - 8, 6, pw + 16, 238, rx=6, ry=6, fillColor=white, strokeColor=LINE, strokeWidth=1))
    secs = [  # (подпись, высота, цвет, тип)
        ("Роль и контекст", 30, B_CTX, "solid"),
        ("<отчётность>", 76, None, "doc"),
        ("Задача", 28, B_TASK, "solid"),
        ("Формат · Ограничения", 28, B_LIM, "solid"),
        ("<пример> … </пример>", 28, B_EX, "solid"),
    ]
    y = 236; centers = []
    for lab, hh, c, kind in secs:
        y -= hh
        if kind == "doc":
            d.add(Rect(px, y, pw, hh, rx=4, ry=4, fillColor=LGREY, strokeColor=GREY, strokeWidth=0.6,
                       strokeDashArray=[3, 2]))
            txt(d, px + 8, y + hh - 13, "<отчётность>", 7.6, GREY, "DV-M")
            for k in range(4):
                d.add(Line(px + 10, y + hh - 24 - k * 9, px + pw - 14 - (k % 2) * 40, y + hh - 24 - k * 9,
                           strokeColor=HexColor("#C4C9D0"), strokeWidth=2.4))
            txt(d, px + 8, y + 5, "</отчётность>", 7.6, GREY, "DV-M")
        else:
            rbox(d, px, y, pw, hh, c, [lab], fs=8.2, r=4)
        centers.append(y + hh / 2)
        y -= 6
    nx = 290
    notes = [
        (centers[1], ["Длинные данные — ближе к началу:", "документ, таблица, переписка"]),
        (centers[1] - 30, ["Теги отделяют данные от инструкций —", "модель не перепутает, где что"]),
        (centers[2], ["Главный вопрос — ближе к концу,", "после материалов"]),
        (centers[4], ["Образец результата —", "в отдельном блоке"]),
    ]
    for cy, ln in notes:
        arrow(d, nx - 4, cy, px + pw + 6, cy, GREY, 0.9, 5)
        txt(d, nx, cy + 2, ln[0], 7.6, INK, "DV-B")
        txt(d, nx, cy - 9, ln[1], 7.2, GREY)
    return d

