# Рис. 1 — два способа научить компьютер
def fig_two_ways():
    d = Drawing(CW, 200)
    pw = (CW - 30) / 2
    for k, (title, ins, out, outc) in enumerate([
        ("Обычная программа", [("Данные", []), ("Правила", ["(пишет человек)"])], "Ответы", TEAL),
        ("Машинное обучение", [("Данные", []), ("Ответы", ["(примеры)"])], "Правила!", CORAL)]):
        x0 = k * (pw + 30)
        d.add(Rect(x0, 0, pw, 200, rx=8, ry=8, fillColor=HexColor("#F7F8FA"), strokeColor=LINE, strokeWidth=0.8))
        txt(d, x0 + pw / 2, 182, title, 9.5, NAVY, "DV-B", "middle")
        bw, bh = 86, 36
        for j, (nm, sub) in enumerate(ins):
            bx = x0 + pw / 2 - bw - 8 + j * (bw + 16)
            rbox(d, bx, 126, bw, bh, NAVY if j == 0 else TEAL, [nm] + sub, fs=8.2)
            arrow(d, bx + bw / 2, 124, x0 + pw / 2, 96, GREY, 1)
        rbox(d, x0 + pw / 2 - 55, 62, 110, 32, HexColor("#334155"), ["Компьютер"], fs=8.6)
        arrow(d, x0 + pw / 2, 60, x0 + pw / 2, 44, GREY, 1.2)
        rbox(d, x0 + pw / 2 - 50, 10, 100, 32, outc, [out], fs=9)
    return d

# Рис. 2 — матрёшка терминов
def fig_matryoshka():
    d = Drawing(CW, 220)
    levels = [("Искусственный интеллект", "любые методы «умного» поведения", HexColor("#DCE6F2"), "Шахматы 1997 г., экспертные системы"),
              ("Машинное обучение", "учится на данных", HexColor("#BFD3EA"), "Скоринг, спам-фильтр, рекомендации"),
              ("Глубокое обучение", "многослойные нейросети", HexColor("#7FA4CC"), "Распознавание лиц и речи, перевод"),
              ("LLM", "", NAVY, "ChatGPT, Claude, Gemini")]
    x, y, w, h = 0, 4, 300, 212
    for i, (nm, sub, c, ex) in enumerate(levels):
        if i == 3:  # LLM — меньше, слева: справа от неё место для генеративного ИИ
            w, h = 112, 52
        d.add(Rect(x, y, w, h, rx=10, ry=10, fillColor=c, strokeColor=white, strokeWidth=1.2))
        tc = white if i == 3 else INK
        ty = y + h - 16
        txt(d, x + 10, ty, nm, 8.8, tc, "DV-B")
        if sub:
            txt(d, x + 10, ty - 11, sub, 7.2, tc if i == 3 else GREY)
        d.add(Line(x + w, ty - 3, 318, ty - 3, strokeColor=GREY, strokeWidth=0.6, strokeDashArray=[2, 2]))
        txt(d, 324, ty - 6, ex, 7.6, INK)
        x += 18; y += 6; w -= 36; h -= 46
    # генеративный ИИ — не уровень матрёшки, а группа по назначению: включает LLM и модели картинок, звука, видео
    gx, gy, gw, gh = 46, 18, 212, 80
    d.add(Rect(gx, gy, gw, gh, rx=10, ry=10, fillColor=None, strokeColor=GOLD, strokeWidth=1.8,
               strokeDashArray=[4, 3]))
    txt(d, 172, gy + gh - 15, "Генеративный ИИ", 8.2, white, "DV-B")
    txt(d, 172, gy + gh - 26, "создаёт тексты, код,", 7, white)
    txt(d, 172, gy + gh - 36, "картинки, музыку", 7, white)
    d.add(Line(gx + gw, gy + gh - 18, 318, gy + gh - 18, strokeColor=GREY, strokeWidth=0.6, strokeDashArray=[2, 2]))
    txt(d, 324, gy + gh - 21, "LLM, генераторы картинок и звука", 7.6, INK)
    return d

# Рис. 3 — вехи развития
def fig_timeline():
    d = Drawing(CW, 160)
    ev = [("1950", ["Тест Тьюринга:", "«Может ли машина", "мыслить?»"]),
          ("1956", ["Рождение термина", "«искусственный", "интеллект»"]),
          ("1970–90", ["Экспертные", "системы и", "«зимы ИИ»"]),
          ("1997", ["Deep Blue", "обыгрывает", "Каспарова"]),
          ("2012", ["Прорыв глубокого", "обучения в", "распознавании"]),
          ("2017", ["Архитектура", "«Трансформер»"]),
          ("2022", ["ChatGPT —", "ИИ для всех"]),
          ("2024–26", ["Мультимодальность,", "рассуждение,", "агенты"])]
    y0 = 80
    d.add(Line(8, y0, CW - 8, y0, strokeColor=NAVY, strokeWidth=2))
    step = (CW - 40) / (len(ev) - 1)
    for i, (yr, lines) in enumerate(ev):
        x = 20 + i * step
        c = CORAL if yr in ("1970–90",) else (TEAL if i < 6 else GOLD)
        d.add(Circle(x, y0, 6, fillColor=c, strokeColor=white, strokeWidth=1.5))
        up = i % 2 == 0
        txt(d, x, y0 + 14 if up else y0 - 22, yr, 8.4, NAVY, "DV-B", "middle")
        for k, ln in enumerate(lines):
            yy = (y0 + 28 + (len(lines) - 1 - k) * 10) if up else (y0 - 34 - k * 10)
            txt(d, x, yy, ln, 6.9, INK, "DV", "middle")
    return d

