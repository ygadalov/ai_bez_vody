# Рис. 5 — нейросеть
def fig_network():
    d = Drawing(CW, 175)
    layers = [3, 5, 5, 2]
    xs = [70, 190, 310, 430]
    pts = []
    for li, n in enumerate(layers):
        pts.append([(xs[li], 95 + (k - (n - 1) / 2) * 28) for k in range(n)])
    for a, b in zip(pts, pts[1:]):
        for p in a:
            for q in b:
                d.add(Line(p[0], p[1], q[0], q[1], strokeColor=HexColor("#B8C4D4"), strokeWidth=0.6))
    for li, col in enumerate(pts):
        for p in col:
            d.add(Circle(p[0], p[1], 9, fillColor=GOLD if li in (0, 3) else TEAL, strokeColor=white, strokeWidth=1))
    txt(d, xs[0], 12, "вход", 8, NAVY, "DV-B", "middle")
    txt(d, (xs[1] + xs[2]) / 2, 12, "скрытые слои", 8, NAVY, "DV-B", "middle")
    txt(d, xs[3], 12, "выход", 8, NAVY, "DV-B", "middle")
    return d

# Рис. 6 — цикл обучения
def fig_cycle():
    d = Drawing(CW, 110)
    steps = [("1. Угадать", NAVY), ("2. Сравнить с", TEAL), ("3. Посчитать", GOLD), ("4. Чуть подкрутить", CORAL)]
    subs = [[], ["правильным ответом"], ["ошибку"], ["веса"]]
    bw, gap = 104, (CW - 4 * 104) / 3
    for i, ((nm, c), sub) in enumerate(zip(steps, subs)):
        x = i * (bw + gap)
        rbox(d, x, 52, bw, 40, c, [nm] + sub, fs=8, fc=INK if c == GOLD else white)
        if i < 3:
            arrow(d, x + bw + 3, 72, x + bw + gap - 3, 72, GREY, 1.2)
    d.add(Line(CW - bw / 2, 50, CW - bw / 2, 30, strokeColor=GREY, strokeWidth=1))
    d.add(Line(CW - bw / 2, 30, bw / 2, 30, strokeColor=GREY, strokeWidth=1))
    arrow(d, bw / 2, 30, bw / 2, 50, GREY, 1)
    txt(d, CW / 2, 14, "…и так миллионы раз, пока ошибка не станет маленькой", 7.8, GREY, "DV-I", "middle")
    return d

