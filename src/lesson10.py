# Рис. 2 — цикл агента
def fig_cycle():
    d = Drawing(CW, 190)
    # человек на входе и на выходе
    rbox(d, 0, 128, 96, 52, B_FMT, ["Вы:", "задача и", "границы"], fs=7.4, lead=10.5)
    rbox(d, 0, 8, 96, 52, B_FMT, ["Вы:", "diff, приёмка,", "коммит"], fs=7.4, lead=10.5)
    # цикл агента
    steps = [["1. План:", "что меняем"], ["2. Правки", "файлов"], ["3. Запуск", "скрипта"],
             ["4. Чтение", "результата"], ["5. Ошибка?", "чиним и к шагу 2"]]
    cols = [NAVY, PURPLE, TEAL, HexColor("#3E9C93"), CORAL]
    gap = 10
    bw = (CW - 116 - 4 * gap) / 5
    y = 108
    for i, (ln, c) in enumerate(zip(steps, cols)):
        x = 116 + i * (bw + gap)
        rbox(d, x, y, bw, 52, c, ln, fs=7.2, lead=10.5)
        if i < 4:
            arrow(d, x + bw + 1, y + 26, x + bw + gap - 1, y + 26, GREY, 1, 4)
    # вход и выход
    arrow(d, 98, 154, 114, 134, GREY)
    arrow(d, 116 + 4 * (bw + gap) + bw / 2, y - 2, 96, 34, GREY, 1.2)
    # возврат цикла
    x5 = 116 + 4 * (bw + gap) + bw / 2
    x2 = 116 + (bw + gap) + bw / 2
    d.add(Line(x5, y, x5, 78, strokeColor=CORAL, strokeWidth=1.2, strokeDashArray=[3, 2]))
    d.add(Line(x5, 78, x2, 78, strokeColor=CORAL, strokeWidth=1.2, strokeDashArray=[3, 2]))
    arrow(d, x2, 78, x2, y, CORAL, 1.2)
    txt(d, x2 - 6, 70, "пока тесты не пройдут —", 6.8, GREY, "DV-I", "end")
    txt(d, x2 - 6, 60, "без человека внутри цикла", 6.8, GREY, "DV-I", "end")
    # рамка «руки агента»
    d.add(Rect(108, 92, CW - 108, 76, rx=8, ry=8, fillColor=None, strokeColor=TEAL, strokeWidth=1, strokeDashArray=[4, 3]))
    txt(d, CW - 14, 172, "РУКИ АГЕНТА: файлы + командная строка", 7.2, DTEAL, "DV-B", "end")
    return d


# Рис. 3 — лента коммитов и откат
def fig_git():
    d = Drawing(CW, 158)
    commits = [("c1", "проект из урока 9:", "приёмка пройдена", NAVY),
               ("c2", "добавили слайд 12:", "план на месяц", TEAL),
               ("c3", "агент «улучшил»", "форматирование", CORAL)]
    bw, bh, gap = 128, 56, 34
    x0 = 6
    y = 84
    for i, (tag, l1, l2, c) in enumerate(commits):
        x = x0 + i * (bw + gap)
        rbox(d, x, y, bw, bh, c, [tag, l1, l2], fs=7.2, lead=10.5)
        if i < 2:
            arrow(d, x + bw + 2, y + bh / 2, x + bw + gap - 2, y + bh / 2, GREY)
    txt(d, CW - 4, y + bh + 10, "каждый коммит — снимок всего проекта, время идёт →", 7.2, GREY, "DV-I", "end")
    # откат от c3 к c2
    x3 = x0 + 2 * (bw + gap) + bw / 2
    x2 = x0 + (bw + gap) + bw / 2
    d.add(Line(x3, y - 2, x3, 44, strokeColor=CORAL, strokeWidth=1.2, strokeDashArray=[3, 2]))
    d.add(Line(x3, 44, x2, 44, strokeColor=CORAL, strokeWidth=1.2, strokeDashArray=[3, 2]))
    arrow(d, x2, 44, x2, y - 2, CORAL, 1.2)
    txt(d, (x2 + x3) / 2, 30, "откат: проект вернулся к снимку c2,", 7, CORAL, "DV-I", "middle")
    txt(d, (x2 + x3) / 2, 20, "«улучшения» как не бывало", 7, CORAL, "DV-I", "middle")
    rbox(d, x0, 8, bw, 40, LGREY, ["diff c2→c3:", "что именно поменял", "агент — видно всё"], fs=7, fc=INK,
         stroke=LINE, lead=10, bold_first=True)
    return d


