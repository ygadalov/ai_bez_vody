def fig_steps():
    d = Drawing(CW, 120)
    steps = [["1. Прочитать", "и проверить", "исходники"], ["2. Посчитать", "показатели"], ["3. Заполнить", "один слайд"],
             ["4. Все таблицы", "и тексты"], ["5. Графики"], ["6. Слайд", "контроля"]]
    cols = [TEAL, HexColor("#3E9C93"), NAVY, NAVY, PURPLE, B_FMT]
    gap = 10; bw = (CW - 5 * gap) / 6; y = 56; bh = 46
    for i, (ln, c) in enumerate(zip(steps, cols)):
        x = i * (bw + gap)
        rbox(d, x, y, bw, bh, c, ln, fs=7.2, lead=10.5)
        if i < 5:
            arrow(d, x + bw + 1, y + bh / 2, x + bw + gap - 1, y + bh / 2, GREY, 1, 4)
        d.add(Circle(x + bw / 2, 34, 9, fillColor=GOLD, strokeColor=GOLD))
        txt(d, x + bw / 2 + 0.5, 31, "▶", 7.5, NAVY, "DV-B", "middle")
        d.add(Line(x + bw / 2, 43, x + bw / 2, y, strokeColor=GOLD, strokeWidth=1))
        txt(d, x + bw / 2, 14, "запуск и", 6.8, GREY, "DV-I", "middle")
        txt(d, x + bw / 2, 5, "проверка", 6.8, GREY, "DV-I", "middle")
    return d


