# -*- coding: utf-8 -*-
"""Создаёт выдуманные исходники за два месяца: data/2026-08 и data/2026-09.

Структура повторяет типичную «управленку» холдинга: сводка, динамика, листы направлений,
долговая нагрузка и отдельный файл с комментариями подразделений. Все цифры выдуманы.
Запуск: python make_demo_data.py
"""
from pathlib import Path
from openpyxl import Workbook
from openpyxl.styles import Font

HERE = Path(__file__).parent
MONTHS = ["Янв", "Фев", "Мар", "Апр", "Май", "Июн", "Июл", "Авг", "Сен"]

# выручка по месяцам, млн руб.: флот, ж/д, элеваторы
DYN = {
    "Флот": [410, 395, 430, 452, 470, 488, 501, 495, 512],
    "Ж/д перевозки": [620, 605, 640, 655, 671, 690, 702, 715, 728],
    "Элеваторы": [180, 150, 140, 120, 110, 135, 260, 340, 365],
}
PLAN = {"Флот": [480, 500], "Ж/д перевозки": [700, 720], "Элеваторы": [320, 400]}   # план на авг, сен
EBITDA_SHARE = {"Флот": 0.31, "Ж/д перевозки": 0.24, "Элеваторы": 0.38}

DIVISIONS = {
    "Флот": [("Судов в эксплуатации, шт.", [14, 14]), ("Загрузка флота, %", [86.5, 89.0]),
             ("Средняя ставка фрахта, тыс. руб./сут", [1840, 1905])],
    "Ж/д перевозки": [("Вагонов в парке, шт.", [3120, 3150]), ("Оборот вагона, сут", [11.8, 11.2]),
                      ("Простой в ремонте, вагоно-сут", [2410, 2185])],
    "Элеваторы": [("Принято зерна, тыс. т", [412, 538]), ("Отгружено зерна, тыс. т", [305, 377]),
                  ("Загрузка мощностей, %", [61.0, 78.5])],
}
# названия листов: в Excel нельзя использовать «/» в имени листа
SHEET = {"Флот": "Флот", "Ж/д перевозки": "ЖД", "Элеваторы": "Элеваторы"}
DEBT = {"Долг, млн руб.": [9850, 9720], "EBITDA за 12 мес., млн руб.": [3120, 3185]}

COMMENTS = {
    "Флот": ["Загрузка выросла за счёт двух долгосрочных контрактов на перевозку зерна.",
             "Загрузка выросла до 89% после выхода двух судов из планового ремонта."],
    "Ж/д перевозки": ["Простой в ремонте снизился после перехода на сервисный договор с депо.",
                      "Оборот вагона сократился до 11,2 суток за счёт маршрутных отправок."],
    "Элеваторы": ["Начало приёмки урожая: загрузка мощностей растёт по графику.",
                  "Пик приёмки урожая; отставание от плана — из-за поздней уборки в регионе."],
}


def bold_header(ws):
    for c in ws[1]:
        c.font = Font(bold=True)


def make_month(folder: Path, k: int):
    """k = 0 — август (8 месяцев динамики), k = 1 — сентябрь (9 месяцев)."""
    folder.mkdir(parents=True, exist_ok=True)
    n = 8 + k
    wb = Workbook()

    ws = wb.active
    ws.title = "Сводка"
    ws.append(["Направление", "План выручки, млн руб.", "Факт выручки, млн руб.", "EBITDA, млн руб."])
    tot = [0, 0, 0]
    for name in DYN:
        plan, fact = PLAN[name][k], DYN[name][n - 1]
        ebitda = round(fact * EBITDA_SHARE[name])
        ws.append([name, plan, fact, ebitda])
        tot = [tot[0] + plan, tot[1] + fact, tot[2] + ebitda]
    ws.append(["Итого", *tot])
    bold_header(ws)

    ws = wb.create_sheet("Динамика")
    ws.append(["Месяц", *DYN.keys()])
    for i in range(n):
        ws.append([MONTHS[i], *[DYN[name][i] for name in DYN]])
    bold_header(ws)

    for name, rows in DIVISIONS.items():
        ws = wb.create_sheet(SHEET[name])
        ws.append(["Показатель", "Прошлый месяц", "Текущий месяц"])
        for label, vals in rows:
            prev = vals[k - 1] if k else round(vals[0] * 0.97, 1)
            ws.append([label, prev, vals[k]])
        bold_header(ws)

    ws = wb.create_sheet("Долг")
    ws.append(["Показатель", "Значение"])
    for label, vals in DEBT.items():
        ws.append([label, vals[k]])
    ws.append(["Ковенант Долг/EBITDA, не более", 3.5])
    bold_header(ws)
    wb.save(folder / "upravlenka.xlsx")

    wb = Workbook()
    ws = wb.active
    ws.title = "Комментарии"
    ws.append(["Слайд", "Подразделение", "Текст"])
    for name, texts in COMMENTS.items():
        ws.append([name, f"Дирекция «{name}»", texts[k]])
    ws.append(["Выводы", "Финансовая дирекция",
               "Выручка холдинга растёт третий месяц подряд; основной вклад — ж/д перевозки. "
               "Элеваторы отстают от плана из-за поздней уборки, ожидаем восполнения в октябре."
               if k else
               "Выручка выше прошлого месяца по всем направлениям, кроме флота. "
               "Сезон приёмки зерна начался по графику."])
    bold_header(ws)
    wb.save(folder / "kommentarii.xlsx")


if __name__ == "__main__":
    make_month(HERE / "data" / "2026-08", 0)
    make_month(HERE / "data" / "2026-09", 1)
    print("Готово: data/2026-08 и data/2026-09")
